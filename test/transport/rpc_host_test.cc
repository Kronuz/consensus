bool reader() {
	constexpr std::uint32_t L = 2;
	Host one(1, L), two(2, L);
	Server server;
	one.open(addresses({&two}));
	two.open(addresses({&one}));
	server.install(*two.transport);
	one.start();
	two.start();
	auto warm = start_call(one, 2, echo, 64, 10s);
	const bool warmed = until([&] { return warm->done.load(); }, 10s);
	const auto other = 1 - two.transport->loop_of_node(1);
	std::atomic<bool> held{true};
	two.post(other, [&] {
		while (held)
			std::this_thread::sleep_for(1ms);
	});
	std::uint64_t worst = 0;
	bool all = true;
	for (int i = 0; i != 10; ++i) {
		auto c = start_call(one, 2, echo, 4096, 10s);
		all &= until([&] { return c->done.load(); }, 5s) && c->status.outcome == rpc::Outcome::ok && !c->mismatched;
		worst = std::max<std::uint64_t>(worst, std::uint64_t(std::chrono::duration_cast<std::chrono::milliseconds>(c->finished - c->started).count()));
	}
	held = false;
	const bool ok = warmed && all && worst < 200;
	std::printf("reader: with host 2's other loop held, 10 calls completed %s, the slowest in %llu ms %s\n", all ? "yes" : "NO",
				(unsigned long long)worst, ok ? "ok" : "FAILED");
	one.stop();
	two.stop();
	return ok;
}

int main(int argc, char **argv) {
	if (argc != 3 && argc != 4) {
		std::fprintf(stderr, "usage: %s <fixture dir> calls|group-full|call-full|lane-only|stream|local-throw|stalled-peer|hold|idle-race|shutdown|fetch|reader|stop-drain\n", argv[0]);
		return 2;
	}
#ifndef SO_NOSIGPIPE
	std::signal(SIGPIPE, SIG_IGN);  // the host's duty where SO_NOSIGPIPE is missing (connection.h)
#endif
	fixture = argv[1];
	const std::string which = argv[2];
	self = argv[0];
	watchdog(std::chrono::seconds(120));
	if (which == "serve-stopped" && argc == 4)
		return serve_stopped(std::uint16_t(std::strtoul(argv[3], nullptr, 10)));
	bool ok;
	if (which == "calls")
		ok = calls();
	else if (which == "group-full")
		ok = group_full();
	else if (which == "call-full")
		ok = call_full();
	else if (which == "lane-only")
		ok = lane_only();
	else if (which == "stream")
		ok = stream();
	else if (which == "local-throw")
		ok = local_throw();
	else if (which == "stalled-peer")
		ok = stalled_peer();
	else if (which == "hold")
		ok = hold();
	else if (which == "idle-race")
		ok = idle_race();
	else if (which == "reader")
		ok = reader();
	else if (which == "shutdown")
		ok = shutdown();
	else if (which == "fetch")
		ok = fetch();
	else if (which == "stop-drain")
		ok = stop_drain();
	else
		return 2;
	std::fflush(stdout);
	return ok ? 0 : 1;
}
