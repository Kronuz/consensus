// The longest each loop went without turning, in ms: a probe posted every 5 ms, timed to its run.
class Turns {
	struct Probe {
		std::atomic<std::int64_t> posted{-1};  // ms since `began`, -1 when none waits
		std::atomic<std::uint64_t> worst{0};
	};
	std::vector<std::pair<Host *, std::uint32_t>> loops_;
	std::shared_ptr<std::vector<Probe>> probes_;
	steady::time_point began_ = steady::now();
	std::atomic<bool> done_{false};
	std::thread thread_;

public:
	explicit Turns(std::vector<std::pair<Host *, std::uint32_t>> loops)
		: loops_(std::move(loops)), probes_(std::make_shared<std::vector<Probe>>(loops_.size())) {
		thread_ = std::thread([this] {
			while (!done_) {
				for (std::size_t i = 0; i != loops_.size(); ++i) {
					auto &p = (*probes_)[i];
					const auto now = std::int64_t(ms_since(began_));
					if (const auto at = p.posted.load(); at >= 0) {
						p.worst = std::max<std::uint64_t>(p.worst, std::uint64_t(now - at));
						continue;
					}
					p.posted = now;
					loops_[i].first->post(loops_[i].second, [probes = probes_, began = began_, i] {
						auto &q = (*probes)[i];
						q.worst = std::max<std::uint64_t>(q.worst, ms_since(began) - std::uint64_t(q.posted.load()));
						q.posted = -1;
					});
				}
				std::this_thread::sleep_for(5ms);
			}
		});
	}
	std::uint64_t worst(std::size_t i) const { return (*probes_)[i].worst; }
	void stop() {
		if (!done_.exchange(true))
			thread_.join();
	}
	~Turns() { stop(); }
};

// D8, A4: fetch beside a maximal upload on one Bulk connection, against heartbeats.
// RPC_HOST_FETCH_SLOW_READ=ms makes building the 16 MiB reply that much slower.
bool fetch() {
#ifndef SO_NOSIGPIPE
	// A write() to a peer that closed raises SIGPIPE here: the host ignores it (main).
	std::raise(SIGPIPE);
#endif
	constexpr std::uint32_t L = 2;
	const std::string expected = bytes_at(0, 16 << 20);
	const auto *slow_read = std::getenv("RPC_HOST_FETCH_SLOW_READ");
	const auto slow_ms = std::chrono::milliseconds(slow_read ? std::strtoull(slow_read, nullptr, 10) : 0);
	std::atomic<std::uint64_t> built_ms{0}, on_loop{0};
	auto build = [&expected, &built_ms, slow_ms](std::string_view name) -> std::optional<std::string> {
		if (name == "throws")
			throw std::runtime_error("the disk broke");
		if (name == "big") {
			const auto t = steady::now();
			std::this_thread::sleep_for(slow_ms);
			std::string bytes = expected;
			built_ms = std::max<std::uint64_t>(built_ms, ms_since(t));
			return bytes;
		}
		if (name == "huge")
			return std::string(48 << 20, 'h');
		if (name == "slow")
			return expected.substr(0, 4 << 20);
		return std::nullopt;
	};
	// The replies are built before the loops start and the reader moves one out, so no
	// connection's loop builds 16 MiB: a host serves from memory (docs/mechanisms/peer-fetch.md).
	// A name asked past them builds on the loop, counted.
	std::mutex mutex;
	std::map<std::string, std::vector<std::string>, std::less<>> ready;
	for (auto [name, n] : {std::pair{"big", 2}, {"huge", 1}, {"slow", 5}})
		for (int i = 0; i != n; ++i)
			ready[name].push_back(*build(name));
	Host one(1, L), two(2, L);
	HostTransportOptions client, server;
	client.rpc.fetch_bytes = 32 << 20;
	server.rpc.reader = [&mutex, &ready, &build, &on_loop](std::string_view name) -> std::optional<std::string> {
		{
			std::lock_guard hold(mutex);
			if (auto it = ready.find(name); it != ready.end() && !it->second.empty()) {
				auto bytes = std::move(it->second.back());
				it->second.pop_back();
				return bytes;
			}
		}
		auto bytes = build(name);
		on_loop += bytes.has_value();
		return bytes;
	};
	one.open(addresses({&two}), client);
	two.open(addresses({&one}), server);
	const auto reader = one.transport->loop_of_node(2);
	const auto beat = groups_on(L, reader, 1)[0];
	const auto uploads = groups_on(L, 1 - reader, 4);
	for (auto *h : {&one, &two}) {
		h->stores({beat});
		h->stores(uploads);
	}
	Beats beats;
	std::atomic<std::uint64_t> uploaded{0};
	for (std::uint32_t k = 0; k != L; ++k)
		one.transport->on_deliver(k, [&](const Received &r) {
			if (r.route.group == beat)
				beats.beat();
			else
				uploaded += r.payload.size();
			return true;
		});
	one.start();
	two.start();
	const auto hb = two.transport->loop_of_group(beat), up = two.transport->loop_of_group(uploads[0]);
	auto heartbeat = [&] { two.post(hb, [&] { two.transport->send(hb, LinkLane::Control, FrameKind::control, {beat, 2, 1}, 1, "beat"); }); };
	// A burst is 4 groups x 8 frames of 1 MiB, one frame per turn of the loop: a heartbeat posted
	// meanwhile waits for one frame, not the burst.
	std::function<void(std::size_t)> upload_frame = [&](std::size_t i) {
		two.transport->send(up, LinkLane::Bulk, FrameKind::data, {uploads[i / 8], 2, 1}, 1, std::string(1 << 20, 'u'));
		if (i + 1 != uploads.size() * 8)
			two.post(up, [&upload_frame, i] { upload_frame(i + 1); });
	};
	auto upload = [&] { two.post(up, [&] { upload_frame(0); }); };
	if (!until([&] { heartbeat(); return beats.count > 0; }, 10s))
		return false;
	beats.worst = 0;
	Lag lag;
	Turns turns({{&one, reader}, {&two, two.transport->loop_of_node(1)}});
	struct Got {
		std::atomic<bool> done{false};
		std::error_code error;
		std::optional<std::string> bytes;
	};
	auto fetch = [&](const char *name) {
		auto got = std::make_shared<Got>();
		one.at(2, [&] {
			one.transport->fetch(2, name, [got](std::error_code e, std::optional<std::string> b) {
				got->error = e;
				got->bytes = std::move(b);
				got->done = true;
			});
			return 0;
		});
		return got;
	};
	// Uploads start 200 ms before the fetch, heartbeats throughout.
	const auto start = steady::now();
	std::shared_ptr<Got> big;
	std::uint64_t before = 0;
	steady::time_point began = start;
	for (std::int64_t tick = 0; !(big && big->done) && ms_since(start) < 30'000; ++tick) {
		if (tick == 2) {
			before = uploaded.load();
			began = steady::now();
			big = fetch("big");
		}
		heartbeat();
		if (tick % 2 == 0)
			upload();
		std::this_thread::sleep_until(start + (tick + 1) * 100ms);
	}
	const auto fetched_ms = ms_since(began);
	const std::uint64_t turned[] = {turns.worst(0), turns.worst(1)};
	const auto beside = uploaded.load() - before;
	const bool exact = big && big->done && !big->error && big->bytes && *big->bytes == expected;
	auto missing = fetch("none"), throws = fetch("throws"), huge = fetch("huge");
	std::vector<std::shared_ptr<Got>> slow;
	for (int i = 0; i != 5; ++i)
		slow.push_back(fetch("slow"));
	const bool ended = until([&] {
		bool all = missing->done && throws->done && huge->done;
		for (auto &g : slow)
			all &= g->done.load();
		return all;
	}, 30s);
	int busy = 0, slow_ok = 0;
	const auto first_4 = expected.substr(0, 4 << 20);
	for (auto &g : slow) {
		busy += g->error == std::errc::resource_unavailable_try_again;
		slow_ok += !g->error && g->bytes && *g->bytes == first_4;
	}
	// The same name again: the reader must not serve a reply it already moved out.
	auto again = fetch("big");
	const bool again_exact = until([&] { return again->done.load(); }, 30s) && !again->error && again->bytes && *again->bytes == expected;
	const bool table = ended && !missing->error && !missing->bytes && throws->error == std::errc::io_error &&
					   huge->error == std::errc::message_size && busy >= 1 && busy + slow_ok == 5 && again_exact;
	const auto lagged = lag.stop();
	turns.stop();
	const auto bound = 1000 + lagged;
	const bool ok = exact && beside > 0 && beats.worst < bound && table;
	std::printf("fetch: the 16 MiB reply took %llu ms to build, replies built on host 2's loop %llu; the links' loops' longest turn "
				"until it arrived: host 1's %llu ms, host 2's %llu ms (in the whole case: %llu, %llu)\n",
				(unsigned long long)built_ms.load(), (unsigned long long)on_loop.load(), (unsigned long long)turned[0],
				(unsigned long long)turned[1], (unsigned long long)turns.worst(0), (unsigned long long)turns.worst(1));
	const auto big_error = !big || !big->done ? std::string("not done") : big->error ? big->error.message() : std::string("ok");
	std::printf("fetch: 16 MiB arrived exact %s (%s) in %llu ms beside %llu MiB of group uploads on Bulk; links %llu+%llu, "
				"ended dead %llu, stuck %llu, failed %llu; dropped %llu, overrun %llu; heartbeats' longest gap %llu ms of %llu allowed (1000 plus the host's %llu ms of lag); missing %s, "
				"a throwing reader %s, 48 MiB over 32 MiB %s, five 4 MiB at once: %d ok, %d refused; the 16 MiB again exact %s %s\n",
				exact ? "yes" : "NO", big_error.c_str(), (unsigned long long)fetched_ms, (unsigned long long)(beside >> 20),
				(unsigned long long)one.total(&HostTransportStats::links), (unsigned long long)two.total(&HostTransportStats::links),
				(unsigned long long)(one.total(&HostTransportStats::dead) + two.total(&HostTransportStats::dead)),
				(unsigned long long)(one.total(&HostTransportStats::stuck) + two.total(&HostTransportStats::stuck)),
				(unsigned long long)(one.total(&HostTransportStats::failed) + two.total(&HostTransportStats::failed)),
				(unsigned long long)(one.total(&HostTransportStats::dropped) + two.total(&HostTransportStats::dropped)),
				(unsigned long long)(one.total(&HostTransportStats::overrun) + two.total(&HostTransportStats::overrun)),
				(unsigned long long)beats.worst, (unsigned long long)bound, (unsigned long long)lagged,
				!missing->error && !missing->bytes ? "nullopt" : "WRONG", throws->error.message().c_str(), huge->error.message().c_str(), slow_ok,
				busy, again_exact ? "yes" : "NO", ok ? "ok" : "FAILED");
	one.stop();
	two.stop();
	return ok;
}

// D8: host 2's reader holds node 1's connection loop 1.5 s past host 1's 1 s dead_after with
// three fetches on the connection, so host 1 ends both links dead (CI's shape, a kernel write
// held that loop 5.2 s): each fetch is asked again on the next connection and ends as it would
// have, the 4 MiB ones exact and the 48 MiB one message_size (control: the fetch not asked again).
bool fetch_dead() {
	constexpr std::uint32_t L = 2;
	const std::string expected = bytes_at(0, 4 << 20);
	Host one(1, L), two(2, L);
	HostTransportOptions client, server;
	client.rpc.fetch_bytes = 32 << 20;
	client.links.connection.dead_after = 1000ms;
	server.links.connection.keepalive = 100ms;  // host 1 hears it every 100 ms but while it is held
	std::atomic<int> held{0};
	server.rpc.reader = [&](std::string_view name) -> std::optional<std::string> {
		if (name == "held" && held++ == 0)
			std::this_thread::sleep_for(1500ms);
		if (name == "huge")
			return std::string(48 << 20, 'h');
		return expected;
	};
	one.open(addresses({&two}), client);
	two.open(addresses({&one}), server);
	one.start();
	two.start();
	struct Got {
		std::atomic<bool> done{false};
		std::error_code error;
		std::optional<std::string> bytes;
	};
	std::vector<std::shared_ptr<Got>> got;
	one.at(2, [&] {
		for (const char *name : {"held", "huge", "big"}) {
			auto g = got.emplace_back(std::make_shared<Got>());
			one.transport->fetch(2, name, [g](std::error_code e, std::optional<std::string> b) {
				g->error = e;
				g->bytes = std::move(b);
				g->done = true;
			});
		}
		return 0;
	});
	const bool ended = until([&] { return got[0]->done && got[1]->done && got[2]->done; }, 30s);
	const auto exact = [&](const Got &g) { return !g.error && g.bytes && *g.bytes == expected; };
	const auto dead = one.total(&HostTransportStats::dead);
	const auto again = one.lane(&LaneStats::fetches_asked_again);
	const bool ok = ended && dead >= 1 && again == 3 && exact(*got[0]) && got[1]->error == std::errc::message_size && exact(*got[2]);
	const auto said = [](const Got &g) { return !g.done ? std::string("not done") : g.error ? g.error.message() : std::string("bytes"); };
	std::printf("fetch-dead: host 2's connection loop held 1500 ms against host 1's 1000 ms dead_after: links ended dead %llu, "
				"links %llu+%llu, fetches asked again %llu; the held 4 MiB %s (%s), 48 MiB over 32 MiB %s, the other 4 MiB %s (%s) %s\n",
				(unsigned long long)dead, (unsigned long long)one.total(&HostTransportStats::links),
				(unsigned long long)two.total(&HostTransportStats::links), (unsigned long long)again, exact(*got[0]) ? "exact" : "NOT EXACT",
				said(*got[0]).c_str(), said(*got[1]).c_str(), exact(*got[2]) ? "exact" : "NOT EXACT", said(*got[2]).c_str(), ok ? "ok" : "FAILED");
	one.stop();
	two.stop();
	return ok;
}

// A fetch from host 1 to node 2 and what it ended with, `ms` after `from`.
struct Fetched {
	std::atomic<bool> done{false};
	std::error_code error;
	std::optional<std::string> bytes;
	steady::time_point at{};
	std::string said() const { return !done ? "not done" : error ? error.message() : bytes ? "bytes" : "nullopt"; }
	std::uint64_t ms(steady::time_point from) const {
		return done ? std::uint64_t(std::chrono::duration_cast<std::chrono::milliseconds>(at - from).count()) : 0;
	}
};
std::shared_ptr<Fetched> fetch_of(Host &one, const char *name) {
	auto f = std::make_shared<Fetched>();
	one.at(2, [&] {
		one.transport->fetch(2, name, [f](std::error_code e, std::optional<std::string> b) {
			f->error = e;
			f->bytes = std::move(b);
			f->at = steady::now();
			f->done = true;
		});
		return 0;
	});
	return f;
}

// A fetch whose connection ends with 2 MiB of a 48 MiB reply in (host 2's reader then holds the
// connection's loop past host 1's dead_after) is asked again and arrives exact: the first
// attempt's bytes are dropped (control: the retry keeps them, no-clear).
bool fetch_partial() {
	const std::string expected = bytes_at(0, 48 << 20);
	Host one(1, 2), two(2, 2);
	HostTransportOptions client, server;
	client.rpc.fetch_bytes = 64 << 20;
	client.links.connection.dead_after = 1000ms;
	server.links.connection.keepalive = 100ms;
	std::atomic<int> held{0}, partials{0};
	server.rpc.reader = [&](std::string_view name) -> std::optional<std::string> {
		if (name == "held") {
			if (held++ == 0)
				std::this_thread::sleep_for(1500ms);
			return std::string("h");
		}
		++partials;
		return expected;
	};
	one.open(addresses({&two}), client);
	two.open(addresses({&one}), server);
	one.start();
	two.start();
	auto partial = fetch_of(one, "partial");
	until([&] { return one.lane(&LaneStats::bytes_in) >= (std::uint64_t(2) << 20) || partial->done; }, 10s);
	const auto in = one.lane(&LaneStats::bytes_in);
	auto h = fetch_of(one, "held");
	const bool ended = until([&] { return partial->done && h->done; }, 30s);
	const bool exact = !partial->error && partial->bytes && *partial->bytes == expected;
	const bool ok = ended && partials == 2 && exact && !h->error && h->bytes == "h";
	std::printf("fetch-partial: %llu KiB of 48 MiB in when the link was held; the reader ran %d times; it ended %s, %s (%zu bytes); held %s %s\n",
				(unsigned long long)(in >> 10), partials.load(), partial->said().c_str(), exact ? "exact" : "NOT EXACT",
				partial->bytes ? partial->bytes->size() : 0, h->said().c_str(), ok ? "ok" : "FAILED");
	one.stop();
	two.stop();
	return ok;
}

// Every connection dies under the fetch: it ends connection_aborted at the second end, asked
// twice and never a third time.
bool fetch_twice() {
	Host one(1, 2), two(2, 2);
	HostTransportOptions client, server;
	client.links.connection.dead_after = 1000ms;
	server.links.connection.keepalive = 100ms;
	std::atomic<int> calls{0};
	server.rpc.reader = [&](std::string_view) -> std::optional<std::string> {
		++calls;
		std::this_thread::sleep_for(1500ms);
		return std::string("x");
	};
	one.open(addresses({&two}), client);
	two.open(addresses({&one}), server);
	one.start();
	two.start();
	const auto start = steady::now();
	auto f = fetch_of(one, "held");
	until([&] { return f->done.load(); }, 20s);
	std::this_thread::sleep_for(1s);
	const auto again = one.lane(&LaneStats::fetches_asked_again);
	const bool ok = f->error == std::errc::connection_aborted && calls == 2 && again == 1;
	std::printf("fetch-twice: every connection held past dead_after: it ended %s after %llu ms, asked again %llu, the reader ran %d times %s\n",
				f->said().c_str(), (unsigned long long)f->ms(start), (unsigned long long)again, calls.load(), ok ? "ok" : "FAILED");
	one.stop();
	two.stop();
	return ok;
}

// The peer's process exits in its reader: the connection ends, the redial is refused, and the
// fetch ends connection_aborted at once, not at its 4 s fetch_deadline (control: ea48bc8).
bool fetch_gone() {
	Host one(1, 1);
	const auto child = spawn_child(one, "fetch-gone");
	if (!child.pid)
		return false;
	HostTransportOptions options;
	options.rpc.fetch_deadline = 4s;
	one.open({{2, {"127.0.0.1", child.port}}}, options);
	one.start();
	auto first = fetch_of(one, "small");
	until([&] { return first->done.load(); }, 10s);
	const auto start = steady::now();
	auto f = fetch_of(one, "gone");
	until([&] { return f->done.load(); }, 10s);
	const auto again = one.lane(&LaneStats::fetches_asked_again);
	const bool ok = child.port && first->bytes && f->error == std::errc::connection_aborted && f->ms(start) < 1000 && again == 1;
	std::printf("fetch-gone: first fetch %s; the peer's process exits in its reader: it ended %s after %llu ms of 4000, asked again %llu %s\n",
				first->said().c_str(), f->said().c_str(), (unsigned long long)f->ms(start), (unsigned long long)again, ok ? "ok" : "FAILED");
	one.stop();
	::close(child.pipe);
	int status = 0;
	if (!until([&] { return ::waitpid(child.pid, &status, WNOHANG) == child.pid; }, 10s)) {
		::kill(child.pid, SIGKILL);
		::waitpid(child.pid, &status, 0);
	}
	return ok;
}

// Host 1 reloads trusting only another CA: its link to node 2 aborts, the redial fails the TLS
// verification, and the fetch ends connection_aborted at once, not at its 4 s fetch_deadline
// (control: ea48bc8).
bool fetch_unverified() {
	Host one(1, 2), two(2, 2);
	HostTransportOptions client, server;
	client.rpc.fetch_deadline = 4s;
	server.rpc.reader = [&](std::string_view) -> std::optional<std::string> {
		std::this_thread::sleep_for(500ms);
		return std::string("x");
	};
	one.open(addresses({&two}), client);
	two.open(addresses({&one}), server);
	one.start();
	two.start();
	const auto start = steady::now();
	auto f = fetch_of(one, "held");
	std::this_thread::sleep_for(100ms);
	one.transport->reload(context(names[1], "rogue"));
	until([&] { return f->done.load(); }, 10s);
	std::uint64_t unverified = 0;
	for (std::uint32_t k = 0; k != one.loops.size(); ++k)
		unverified += one.loops[k]->at([&] { return one.transport->link_stats(k).unverified; });
	const auto again = one.lane(&LaneStats::fetches_asked_again);
	const bool ok = unverified >= 1 && f->error == std::errc::connection_aborted && f->ms(start) < 2500 && again == 1;
	std::printf("fetch-unverified: a reload trusting another CA ended %llu links; the fetch ended %s after %llu ms of 4000, asked again %llu %s\n",
				(unsigned long long)unverified, f->said().c_str(), (unsigned long long)f->ms(start), (unsigned long long)again,
				ok ? "ok" : "FAILED");
	one.stop();
	two.stop();
	return ok;
}

// A second ask waiting for its connection: the child host 2 stops itself in its reader, host 1's
// link ends dead, and the redial's TLS handshake waits on the stopped process; then remove_node(2)
// or drain() ends it connection_aborted at once (control: no-again-map, where fail() gives it the
// caller's outcome: not_connected, resource_unavailable_try_again).
bool fetch_waiting(bool drain) {
	const char *act = drain ? "drain()" : "remove_node(2)";
	Host one(1, 1);
	const auto child = spawn_child(one, "fetch-removed");
	if (!child.pid)
		return false;
	HostTransportOptions options;
	options.rpc.fetch_deadline = 10s;
	options.rpc.drain_deadline = 300ms;
	options.links.connection.dead_after = 1000ms;
	one.open({{2, {"127.0.0.1", child.port}}}, options);
	one.start();
	auto first = fetch_of(one, "small");
	until([&] { return first->done.load(); }, 10s);
	auto f = fetch_of(one, "frozen");
	const bool asked = until([&] { return one.lane(&LaneStats::fetches_asked_again) >= 1 || f->done; }, 10s);
	std::this_thread::sleep_for(300ms);
	const bool waiting = !f->done;
	const auto start = steady::now();
	if (drain)
		one.transport->drain();
	else
		one.at(2, [&] {
			one.transport->remove_node(2);
			return 0;
		});
	until([&] { return f->done.load(); }, 15s);
	const bool ok = first->bytes && asked && waiting && f->error == std::errc::connection_aborted && f->ms(start) < 500;
	std::printf("fetch-removed: %s with the second ask waiting for its connection (asked again %s, waiting %s): it ended %s after %llu ms %s\n",
				act, asked ? "yes" : "NO", waiting ? "yes" : "NO", f->said().c_str(), (unsigned long long)f->ms(start),
				ok ? "ok" : "FAILED");
	one.stop();
	::kill(child.pid, SIGCONT);
	::close(child.pipe);
	int status = 0;
	if (!until([&] { return ::waitpid(child.pid, &status, WNOHANG) == child.pid; }, 10s)) {
		::kill(child.pid, SIGKILL);
		::waitpid(child.pid, &status, 0);
	}
	return ok;
}

// remove_node(2) and drain() past drain_deadline end a fetch in flight connection_aborted, never
// asked again (control: ea48bc8, which ends them not_connected and resource_unavailable_try_again),
// and a second ask waiting for its connection too (fetch_waiting).
bool fetch_removed() {
	bool ok = fetch_waiting(false) & fetch_waiting(true);
	for (const bool drain : {false, true}) {
		Host one(1, 2), two(2, 2);
		HostTransportOptions client, server;
		client.rpc.drain_deadline = 300ms;
		server.rpc.reader = [&](std::string_view) -> std::optional<std::string> {
			std::this_thread::sleep_for(1500ms);
			return std::string("x");
		};
		one.open(addresses({&two}), client);
		two.open(addresses({&one}), server);
		one.start();
		two.start();
		const auto start = steady::now();
		auto f = fetch_of(one, "held");
		std::this_thread::sleep_for(200ms);
		if (drain)
			one.transport->drain();
		else
			one.at(2, [&] {
				one.transport->remove_node(2);
				return 0;
			});
		until([&] { return f->done.load(); }, 10s);
		const auto again = one.lane(&LaneStats::fetches_asked_again);
		const bool fine = f->error == std::errc::connection_aborted && f->ms(start) < 1000 && again == 0;
		std::printf("fetch-removed: %s with a fetch in flight: it ended %s after %llu ms, asked again %llu %s\n",
					drain ? "drain() past its 300 ms drain_deadline" : "remove_node(2)", f->said().c_str(),
					(unsigned long long)f->ms(start), (unsigned long long)again, fine ? "ok" : "FAILED");
		ok &= fine;
		one.stop();
		two.stop();
	}
	return ok;
}

// With no link ended, the oversize refusal leaves the connection alone: a 48 MiB reply over the
// 32 MiB fetch_bytes ends message_size and the 4 MiB beside it arrives on the same connection
// (control: oversize-aborts, whose refusal also aborts it). A run where a link ended dead or
// stuck proves nothing either way, and says so.
bool fetch_oversize() {
	const std::string expected = bytes_at(0, 4 << 20);
	Host one(1, 2), two(2, 2);
	HostTransportOptions client, server;
	client.rpc.fetch_bytes = 32 << 20;
	server.rpc.reader = [&](std::string_view name) -> std::optional<std::string> {
		if (name == "huge")
			return std::string(48 << 20, 'h');
		return expected;
	};
	one.open(addresses({&two}), client);
	two.open(addresses({&one}), server);
	one.start();
	two.start();
	auto warm = fetch_of(one, "big");
	until([&] { return warm->done.load(); }, 10s);
	const auto links = one.total(&HostTransportStats::links);
	auto huge = fetch_of(one, "huge"), big = fetch_of(one, "big");
	until([&] { return huge->done && big->done; }, 30s);
	std::this_thread::sleep_for(200ms);
	const auto stalled = one.total(&HostTransportStats::dead) + one.total(&HostTransportStats::stuck) +
						 two.total(&HostTransportStats::dead) + two.total(&HostTransportStats::stuck);
	const auto failed = one.total(&HostTransportStats::failed) + two.total(&HostTransportStats::failed);
	const auto again = one.lane(&LaneStats::fetches_asked_again);
	const bool kept = one.total(&HostTransportStats::links) == links && failed == 0 && again == 0;
	const bool ok = huge->error == std::errc::message_size && big->bytes == expected && (kept || stalled);
	std::printf("fetch-oversize: 48 MiB over 32 MiB %s, the 4 MiB beside it %s; links %llu then %llu, ended failed %llu, asked again %llu: "
				"the connection %s %s\n",
				huge->said().c_str(), big->bytes == expected ? "exact" : "NOT EXACT", (unsigned long long)links,
				(unsigned long long)one.total(&HostTransportStats::links), (unsigned long long)failed, (unsigned long long)again,
				kept ? "stayed" : stalled ? "ended in a stall: inconclusive" : "ENDED", ok ? "ok" : "FAILED");
	one.stop();
	two.stop();
	return ok;
}

// The ways a connection ends under a fetch (docs/mechanisms/rpc-lane.md, A fetch whose connection ends).
bool fetch_ends() { return fetch_partial() & fetch_twice() & fetch_gone() & fetch_unverified() & fetch_removed() & fetch_oversize(); }

// T5: host 2's loop that does not read node 1's connection is held 2 s; calls served on the
// connection's loop keep their latency, since a lane frame never waits on another loop.
bool reader() {
	constexpr std::uint32_t L = 2;
	Host one(1, L), two(2, L);
	Server server;
	one.open(addresses({&two}));
	two.open(addresses({&one}));
	server.install(*two.transport);
	one.start();
	two.start();
	auto warm = start_call(one, 2, echo, 64, 10s);
	const bool warmed = until([&] { return warm->done.load(); }, 10s);
	const auto other = 1 - two.transport->loop_of_node(1);
	std::atomic<bool> held{true};
	two.post(other, [&] {
		while (held)
			std::this_thread::sleep_for(1ms);
	});
	std::uint64_t worst = 0;
	bool all = true;
	for (int i = 0; i != 10; ++i) {
		auto c = start_call(one, 2, echo, 4096, 10s);
		all &= until([&] { return c->done.load(); }, 5s) && c->status.outcome == rpc::Outcome::ok && !c->mismatched;
		worst = std::max<std::uint64_t>(worst, std::uint64_t(std::chrono::duration_cast<std::chrono::milliseconds>(c->finished - c->started).count()));
	}
	held = false;
	const bool ok = warmed && all && worst < 200;
	std::printf("reader: with host 2's other loop held, 10 calls completed %s, the slowest in %llu ms %s\n", all ? "yes" : "NO",
				(unsigned long long)worst, ok ? "ok" : "FAILED");
	one.stop();
	two.stop();
	return ok;
}

