// The RPC lane on the host transport's Bulk connection, over loopback with the TLS fixture, every
// loop on its own thread (docs/mechanisms/rpc-lane.md, On Bulk):
//   calls       deadlines and cancels over shared connections: a caller's deadline ends the
//               server's call, a cancel mid-stream ends both ends once, and every pool is back to 0
//   group-full  a group whose receiving loop is held fills its credit on Bulk; calls on the
//               same connection keep their latency (control: rpc-shared-credit)
//   call-full   a call whose server never reads fills its credit and pool; another group's
//               heartbeats keep every gap under the 1,000 ms election timeout
//   lane-only   two nodes that share no group: a streamed call dials Bulk alone, completes, and
//               no group's counter moves
//   stream      a 32 MiB request streams under the lane's credit (the sender's queued bytes within
//               one window) while heartbeats on Control keep every gap under 1,000 ms plus the
//               host's lag (control: rpc-past-credit)
//   local-throw a handler and a body consumer that throw fail their own call handler_failed; the
//               Bulk connection, a group's frames on it and the next call go on (control:
//               local-throw-closes)
//   stalled-peer a peer that stops reading holds at most its connection's queue of the host's
//               rpc_outgoing_bytes, so a call to another peer goes on (A3; control: rpc-no-queue-cap)
//   hold        T3: hold(node) keeps a lane-only Bulk connection past lane_idle; release drains
//               it, Drain then close_notify (control: hold-ignored)
//   idle-race   D7, T8: host 1's lane_idle drains the connection while host 2, its loop held, starts
//               calls on it: each ends ok or not_processed, never connection_aborted, and the next
//               call dials again (control: rpc-no-drain)
//   shutdown    T8: drain() with a 4 MiB echo in flight: it completes, a new call ends
//               not_processed, and the Bulk connection closes gracefully
//   fetch       D8, A4: fetch is method 1. Beside 4 groups uploading 1 MiB data frames on the same
//               Bulk connection, a 16 MiB fetch arrives exact while heartbeats on Control keep
//               every gap under 1,000 ms plus the host's lag, its replies built before the loops
//               start; a missing name, a reader that throws, a reply over this host's fetch_bytes
//               and a fifth concurrent fetch end as D8's table says, and the 16 MiB fetched again
//               arrives exact; then
//               fetch-dead: host 2's connection loop held past host 1's dead_after ends its links
//               with three fetches on them, and each is asked again and ends as it would have
//               (control: fetch-not-asked-again); then each way a connection ends under a fetch
//               (rpc-lane.md's table): fetch-partial, fetch-twice, fetch-gone, fetch-unverified,
//               fetch-removed and fetch-oversize, each runnable alone for its control
//   reader      T5: with host 2's other loop held 2 s, calls whose frames its connection's loop
//               reads keep their latency (control: lane-via-other-loop)
//   stop-drain  F18, D102: host 2 runs in a child process that stops itself (SIGSTOP) inside its
//               reader; host 1's fetch ends timed_out, and after SIGCONT the late reply drains
//               over the same connection and the next fetch succeeds on it (control:
//               forget-is-violation, the never-drain mutant)
//   consensus_transport_rpc_host_test <fixture dir> case
