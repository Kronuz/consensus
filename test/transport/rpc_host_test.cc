#endif
	fixture = argv[1];
	const std::string which = argv[2];
	self = argv[0];
	watchdog(std::chrono::seconds(120));
	if (which == "serve-stopped" && argc == 4)
		return serve_stopped(std::uint16_t(std::strtoul(argv[3], nullptr, 10)));
	bool ok;
	if (which == "calls")
		ok = calls();
	else if (which == "group-full")
		ok = group_full();
	else if (which == "call-full")
		ok = call_full();
	else if (which == "lane-only")
		ok = lane_only();
	else if (which == "stream")
		ok = stream();
	else if (which == "local-throw")
		ok = local_throw();
	else if (which == "stalled-peer")
		ok = stalled_peer();
	else if (which == "hold")
		ok = hold();
	else if (which == "idle-race")
		ok = idle_race();
	else if (which == "reader")
		ok = reader();
	else if (which == "shutdown")
		ok = shutdown();
	else if (which == "fetch")
		ok = fetch() & fetch_dead() & fetch_ends();
	else if (which == "fetch-dead")  // fetch's parts alone, for their controls
		ok = fetch_dead();
	else if (which == "fetch-partial")
		ok = fetch_partial();
	else if (which == "fetch-twice")
		ok = fetch_twice();
	else if (which == "fetch-gone")
		ok = fetch_gone();
	else if (which == "fetch-unverified")
		ok = fetch_unverified();
	else if (which == "fetch-removed")
		ok = fetch_removed();
	else if (which == "fetch-oversize")
		ok = fetch_oversize();
	else if (which == "stop-drain")
		ok = stop_drain();
