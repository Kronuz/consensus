// F18: the child's host 2 stops the whole process in its reader, so host 1's fetch passes its
// deadline with the Call read and no reply sent. After SIGCONT the reply goes out to a retired id:
// host 1 drops it (rule 9) and keeps the connection, and the next fetch runs on that connection.
const char *self = nullptr;
constexpr std::size_t late_bytes = 64 * 1024;
int serve_stopped(std::uint16_t parent) {
	Host two(2, 1);
	HostTransportOptions options;
	options.rpc.reader = [](std::string_view name) -> std::optional<std::string> {
		if (name == "frozen")
			::raise(SIGSTOP);  // the placed stop: the reply leaves only after SIGCONT
		if (name == "gone")
			::raise(SIGKILL);  // gone at once: TSan's _exit sleeps atexit_sleep_ms (1 s) with the sockets open
		return bytes_at(0, late_bytes);
	};
	two.open({{1, {"127.0.0.1", parent}}}, options);
	two.start();
	std::printf("%u\n", unsigned(two.port()));
	std::fflush(stdout);
	char c;
	while (::read(STDIN_FILENO, &c, 1) > 0) {  // until host 1 closes the pipe
	}
	two.stop();
	return 0;
}
// Host 2 as serve_stopped in a child process dialing `one`: its pid, its port (0 when it did not
// start) and the pipe whose close ends it.
struct Child {
	pid_t pid = 0;
	std::uint16_t port = 0;
	int pipe = -1;
};
Child spawn_child(Host &one, const char *test) {
	Child child;
	int to_child[2], from_child[2];
	if (::pipe(to_child) || ::pipe(from_child))
		return child;
	posix_spawn_file_actions_t actions;
	posix_spawn_file_actions_init(&actions);
	posix_spawn_file_actions_adddup2(&actions, to_child[0], STDIN_FILENO);
	posix_spawn_file_actions_adddup2(&actions, from_child[1], STDOUT_FILENO);
	posix_spawn_file_actions_addclose(&actions, to_child[1]);
	posix_spawn_file_actions_addclose(&actions, from_child[0]);
	const std::string port = std::to_string(one.port());
	char *args[] = {const_cast<char *>(self), const_cast<char *>(fixture.c_str()), const_cast<char *>("serve-stopped"),
					const_cast<char *>(port.c_str()), nullptr};
	const int spawned = ::posix_spawn(&child.pid, self, &actions, nullptr, args, environ);
	posix_spawn_file_actions_destroy(&actions);
	::close(to_child[0]);
	::close(from_child[1]);
	child.pipe = to_child[1];
	if (spawned) {
		std::printf("%s: posix_spawn %s: %s FAILED\n", test, self, std::strerror(spawned));
		::close(from_child[0]);
		return child;
	}
	std::string line;
	for (char c; line.find('\n') == std::string::npos && ::read(from_child[0], &c, 1) == 1;)
		line += c;
	::close(from_child[0]);
	child.port = std::uint16_t(std::strtoul(line.c_str(), nullptr, 10));
	return child;
}
bool stop_drain() {
	Host one(1, 1);
	const auto spawned = spawn_child(one, "stop-drain");
	if (!spawned.pid)
		return false;
	const auto child = spawned.pid;
	const auto child_port = spawned.port;
	HostTransportOptions options;
	options.rpc.fetch_deadline = 1s;
	one.open({{2, {"127.0.0.1", child_port}}}, options);
	one.start();
	struct Got {
		std::atomic<bool> done{false};
		std::error_code error;
		std::optional<std::string> bytes;
	};
	auto fetch = [&](const char *name) {
		auto got = std::make_shared<Got>();
		one.at(2, [&] {
			one.transport->fetch(2, name, [got](std::error_code e, std::optional<std::string> b) {
				got->error = e;
				got->bytes = std::move(b);
				got->done = true;
			});
			return 0;
		});
		until([&] { return got->done.load(); }, 10s);
		return got;
	};
	auto exact = [](const Got &g) { return g.done && !g.error && g.bytes && *g.bytes == bytes_at(0, late_bytes); };
	const bool first = child_port && exact(*fetch("small"));
	const auto links = one.total(&HostTransportStats::links);
	const auto frozen = fetch("frozen");
	int status = 0;
	bool stopped = false;
	until([&] { return stopped = ::waitpid(child, &status, WUNTRACED | WNOHANG) == child && WIFSTOPPED(status); }, 5s);
	const auto before = one.lane(&LaneStats::bytes_in);
	::kill(child, SIGCONT);
	const bool late = until([&] { return one.lane(&LaneStats::bytes_in) >= before + late_bytes; }, 10s);
	const auto again = fetch("small");
	const bool kept = one.total(&HostTransportStats::links) == links && one.ended(rpc::Outcome::connection_aborted) == 0;
	const bool ok = first && stopped && frozen->error == std::errc::timed_out && late && exact(*again) && kept;
	std::printf("stop-drain: first fetch %s; the child stopped in its reader %s, the fetch ended %s; after SIGCONT %llu late "
				"bytes arrived %s; the next fetch %s on the same connection %s (links %llu then %llu) %s\n",
				first ? "ok" : "FAILED", stopped ? "yes" : "NO", frozen->error.message().c_str(),
				(unsigned long long)(one.lane(&LaneStats::bytes_in) - before), late ? "yes" : "NO", exact(*again) ? "ok" : "FAILED",
				kept ? "yes" : "NO", (unsigned long long)links, (unsigned long long)one.total(&HostTransportStats::links),
				ok ? "ok" : "FAILED");
	one.stop();
	::kill(child, SIGCONT);
	::close(spawned.pipe);
	if (!until([&] { return ::waitpid(child, &status, WNOHANG) == child; }, 10s)) {
		::kill(child, SIGKILL);
		::waitpid(child, &status, 0);
	}
	return ok;
}
